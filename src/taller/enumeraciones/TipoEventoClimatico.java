package taller.enumeraciones;

/**
 * Tipo de evento climatico que origina una alerta.
 */
public enum TipoEventoClimatico {
    /** Lluvia intensa, emitida automaticamente por el sistema. */
    LLUVIA_COPIOSA,
    /** Crecida de rio, registrada por un operador. */
    CRECIDA_RIO,
    /** Tormenta severa, registrada por un operador. */
    TORMENTA_SEVERA
}
